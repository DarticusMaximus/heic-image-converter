#[test]
fn manifest_covers_every_fixture_file() {
    let manifest = load_manifest();
    assert_eq!(manifest.version, 1, "manifest schema version");

    let mut in_manifest = BTreeSet::new();
    let mut total_bytes = 0u64;
    for fixture in &manifest.fixtures {
        assert!(
            in_manifest.insert(fixture.file.clone()),
            "manifest lists {} more than once",
            fixture.file
        );
        assert!(
            fixture.bytes > 0,
            "{} has no recorded size; run `cargo test -- --ignored update_fixture_manifest`",
            fixture.file
        );
        assert!(
            !fixture.sha256.is_empty(),
            "{} has no recorded sha256; run `cargo test -- --ignored update_fixture_manifest`",
            fixture.file
        );
        assert!(
            fixture.sha256.len() == 64
                && fixture
                    .sha256
                    .chars()
                    .all(|c| c.is_ascii_hexdigit() && !c.is_ascii_uppercase()),
            "{} sha256 is not 64 lowercase hex characters",
            fixture.file
        );
        assert!(
            fixture.bytes <= MAX_FIXTURE_BYTES,
            "{} is {} bytes, over the {MAX_FIXTURE_BYTES} byte per-fixture budget",
            fixture.file,
            fixture.bytes
        );
        total_bytes += fixture.bytes;

        let kind = InputKind::from_path(Path::new(&fixture.file)).unwrap_or_else(|| {
            panic!(
                "{} does not have an extension the app supports",
                fixture.file
            )
        });
        assert_eq!(
            kind.label(),
            fixture.kind,
            "{} has kind {:?} in the manifest but the app labels it {:?}",
            fixture.file,
            fixture.kind,
            kind.label()
        );
    }

    assert!(
        total_bytes <= MAX_CORPUS_BYTES,
        "corpus totals {total_bytes} bytes, over the {MAX_CORPUS_BYTES} byte budget"
    );

    let on_disk: BTreeSet<String> = directory_fixture_names()
        .expect("read the fixture directory")
        .into_iter()
        .collect();
    let missing: Vec<&String> = in_manifest.difference(&on_disk).collect();
    let stray: Vec<&String> = on_disk.difference(&in_manifest).collect();
    assert!(
        missing.is_empty() && stray.is_empty(),
        "fixture directory and manifest disagree:\n  missing from disk: {missing:?}\n  not in manifest: {stray:?}"
    );
}

#[test]
fn fixtures_match_recorded_bytes_and_hash() {
    let manifest = load_manifest();
    for fixture in &manifest.fixtures {
        let path = fixture_path(&fixture.file);
        let data = std::fs::read(&path)
            .unwrap_or_else(|err| panic!("could not read {}: {err}", path.display()));
        assert_eq!(
            data.len() as u64,
            fixture.bytes,
            "{} is {} bytes on disk but {} bytes in the manifest",
            fixture.file,
            data.len(),
            fixture.bytes
        );
        let actual = sha256_hex(&data);
        assert_eq!(
            actual, fixture.sha256,
            "{} hash drifted; re-run `cargo test -- --ignored update_fixture_manifest` only if the change is intended",
            fixture.file
        );
    }
}

/// Enforce every recorded decode expectation: success, dimensions, colour type,
/// `decode::dimensions` parity, corner colours within tolerance, and the
/// per-channel source depth rule.
#[test]
fn decoded_fixtures_match_recorded_facts() {
    let manifest = load_manifest();
    assert_eq!(
        manifest.corner_tolerance, EXPECTED_CORNER_TOLERANCE,
        "manifest corner_tolerance is {} but the corpus requires {EXPECTED_CORNER_TOLERANCE}; widening it would silently disable the corner checks",
        manifest.corner_tolerance
    );

    for fixture in &manifest.fixtures {
        // Corrupt fixtures are the corrupt-decode test's job.
        if fixture.error.is_some() {
            continue;
        }

        let decoded = fixture.decoded.as_ref().unwrap_or_else(|| {
            panic!(
                "{} has no decode error but no `decoded` block either",
                fixture.file
            )
        });
        let path = fixture_path(&fixture.file);
        let kind = InputKind::from_path(&path).unwrap_or_else(|| {
            panic!(
                "{} does not have an extension the app supports",
                fixture.file
            )
        });

        let image = decode::load(&path, kind)
            .unwrap_or_else(|err| panic!("{}: decode::load failed: {err}", fixture.file));

        // Report both dimension checks together so a broken expectation shows
        // whether the decode path or the dimension-only path is at fault.
        let recorded = (decoded.width, decoded.height);
        let loaded = (image.width(), image.height());
        let listed = decode::dimensions(&path, kind);
        let mut problems = Vec::new();
        if loaded != recorded {
            problems.push(format!(
                "decode::load returned {}x{} but the manifest records {}x{}",
                loaded.0, loaded.1, recorded.0, recorded.1
            ));
        }
        if listed != Some(recorded) {
            problems.push(format!(
                "decode::dimensions returned {listed:?} but the manifest records {recorded:?}"
            ));
        }
        assert!(
            problems.is_empty(),
            "{}: decoded dimensions disagree with the manifest:\n  {}",
            fixture.file,
            problems.join("\n  ")
        );

        let color = color_debug_name(image.color());
        assert_eq!(
            color, decoded.color,
            "{}: decoded color type is {color} but the manifest records {}",
            fixture.file, decoded.color
        );

        let sampled = sample_corners(&image);
        if let Err(detail) = corners_match(&sampled, &decoded.corners, manifest.corner_tolerance) {
            panic!(
                "{}: corners drifted: {detail}\n  sampled: {sampled:?}\n  recorded: {:?}",
                fixture.file, decoded.corners
            );
        }

        // `bit_depth` is the source depth, which a decoded colour type cannot
        // express for 10/12-bit HEIC. HEIC is probed through the seam; every
        // other format is derived from the decoded colour type, which was just
        // asserted equal to `decoded.color`.
        let (measured_depth, rule) = if kind.is_heic() {
            let info = crate::heic::probe(&path)
                .unwrap_or_else(|err| panic!("{}: heic::probe failed: {err}", fixture.file));
            (seam_bit_depth(info.bit_depth), "heic::probe")
        } else {
            (color_derived_bit_depth(image.color()), "decoded color type")
        };
        let recorded_depth = fixture.bit_depth.unwrap_or_else(|| {
            panic!(
                "{} has no decode error but no recorded `bit_depth`",
                fixture.file
            )
        });
        assert_eq!(
            measured_depth, recorded_depth,
            "{}: {rule} puts the source bit depth at {measured_depth} but the manifest records {recorded_depth}",
            fixture.file
        );
    }
}

/// The settings the recorded output facts were measured under: no resize,
/// `Quality::High`, and no output folder (nothing is written to disk).
pub fn output_settings(format: OutputFormat) -> ConvertSettings {
    ConvertSettings {
        format,
        quality: Quality::High,
        max_dimension: None,
        output_dir: None,
        overwrite: false,
    }
}

/// Re-decode encoded bytes in memory, never via a temp file.
pub fn decode_encoded_output(bytes: &[u8], label: &str, file: &str) -> image::DynamicImage {
    image::load_from_memory(bytes).unwrap_or_else(|err| {
        panic!(
            "{file}: {label} output ({} bytes) does not decode back: {err}",
            bytes.len()
        )
    })
}

/// `encode_bytes` reports dimensions from the image it encoded *and* the bytes
/// decode to dimensions of their own; both must match the recorded block. They
/// are compared together so a failure says which of the two disagrees.
pub fn check_output_dimensions(
    file: &str,
    label: &str,
    field: &str,
    returned: (u32, u32),
    redecoded: (u32, u32),
    recorded: (u32, u32),
) {
    let mut problems = Vec::new();
    if returned != recorded {
        problems.push(format!(
            "{label} encode_bytes returned {}x{} but {field} records {}x{}",
            returned.0, returned.1, recorded.0, recorded.1
        ));
    }
    if redecoded != recorded {
        problems.push(format!(
            "{label} output re-decoded to {}x{} but {field} records {}x{}",
            redecoded.0, redecoded.1, recorded.0, recorded.1
        ));
    }
    assert!(
        problems.is_empty(),
        "{file}: {label} output dimensions disagree with the manifest:\n  {}",
        problems.join("\n  ")
    );
}

/// Enforce every recorded conversion output fact: one `convert::encode_bytes`
/// run per output format with no resize and `Quality::High`, re-decoded from
/// memory. PNG output must be 8-bit and keep grayscale/alpha; JPEG output must
/// be `Rgb8`, which is what makes the alpha-onto-white corners provable.
#[test]
fn conversion_outputs_match_recorded_facts() {
    let manifest = load_manifest();
    assert_eq!(
        manifest.corner_tolerance, EXPECTED_CORNER_TOLERANCE,
        "manifest corner_tolerance is {} but the corpus requires {EXPECTED_CORNER_TOLERANCE}; widening it would silently disable the corner checks",
        manifest.corner_tolerance
    );

    let mut checked = 0usize;

    for fixture in &manifest.fixtures {
        // Corrupt fixtures are the corrupt-decode test's job.
        if fixture.error.is_some() {
            continue;
        }
        checked += 1;

        // A non-error fixture without an output block would otherwise skip the
        // encode checks entirely.
        let png = fixture.png_output.as_ref().unwrap_or_else(|| {
            panic!(
                "{} has no decode error but no `png_output` block; every non-error fixture must record one",
                fixture.file
            )
        });
        let jpeg = fixture.jpeg_output.as_ref().unwrap_or_else(|| {
            panic!(
                "{} has no decode error but no `jpeg_output` block; every non-error fixture must record one",
                fixture.file
            )
        });

        let path = fixture_path(&fixture.file);

        // --- PNG: always 8-bit, grayscale and alpha preserved ---
        let (bytes, width, height) =
            convert::encode_bytes(&path, &output_settings(OutputFormat::Png))
                .unwrap_or_else(|err| panic!("{}: PNG encode failed: {err}", fixture.file));
        let image = decode_encoded_output(&bytes, "PNG", &fixture.file);
        check_output_dimensions(
            &fixture.file,
            "PNG",
            "png_output",
            (width, height),
            (image.width(), image.height()),
            (png.width, png.height),
        );
        let color = color_debug_name(image.color());
        assert_eq!(
            color, png.color,
            "{}: png_output re-decoded as color type {color} but the manifest records {}; PNG output is always 8-bit and keeps grayscale/alpha",
            fixture.file, png.color
        );

        // --- JPEG: always Rgb8, alpha composited onto white ---
        let (bytes, width, height) =
            convert::encode_bytes(&path, &output_settings(OutputFormat::Jpeg))
                .unwrap_or_else(|err| panic!("{}: JPEG encode failed: {err}", fixture.file));
        let image = decode_encoded_output(&bytes, "JPEG", &fixture.file);
        check_output_dimensions(
            &fixture.file,
            "JPEG",
            "jpeg_output",
            (width, height),
            (image.width(), image.height()),
            (jpeg.width, jpeg.height),
        );
        let color = color_debug_name(image.color());
        assert_eq!(
            color, "Rgb8",
            "{}: jpeg_output re-decoded as color type {color} but JPEG output is always Rgb8",
            fixture.file
        );

        if let Some(recorded_corners) = &jpeg.corners {
            let sampled = sample_rgb_corners(&image);
            if let Err(detail) =
                rgb_corners_match(&sampled, recorded_corners, manifest.corner_tolerance)
            {
                panic!(
                    "{}: jpeg_output corners drifted: {detail}\n  sampled: {sampled:?}\n  recorded: {recorded_corners:?}",
                    fixture.file
                );
            }
        }
    }

    // The spec records 20 non-error fixtures. Adding or dropping one is a
    // deliberate corpus change; update this count with it.
    assert_eq!(
        checked, 20,
        "conversion outputs were checked for {checked} fixtures but the corpus records 20 non-error fixtures"
    );
}

