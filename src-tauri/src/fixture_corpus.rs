/// Every fixture that records a decode error must really fail to decode, with
/// a message worth showing the user, and the corpus must keep exactly the two
/// corrupt fixtures the spec calls for.
#[test]
fn corrupt_fixtures_fail_to_decode() {
    let manifest = load_manifest();
    let mut corrupt: Vec<&str> = Vec::new();

    for fixture in &manifest.fixtures {
        let Some(error_kind) = fixture.error.as_deref() else {
            continue;
        };
        assert_eq!(
            error_kind, DECODE_ERROR_KIND,
            "{} records error {error_kind:?}, which no integrity test understands",
            fixture.file
        );

        let path = fixture_path(&fixture.file);
        let kind = InputKind::from_path(&path).unwrap_or_else(|| {
            panic!(
                "{} does not have an extension the app supports",
                fixture.file
            )
        });
        match decode::load(&path, kind) {
            Ok(image) => panic!(
                "{} records error {error_kind:?} but decode::load succeeded and returned a {}x{} {} image",
                fixture.file,
                image.width(),
                image.height(),
                color_debug_name(image.color())
            ),
            Err(message) => assert!(
                !message.trim().is_empty(),
                "{} failed to decode as recorded, but the error message is empty",
                fixture.file
            ),
        }

        corrupt.push(fixture.file.as_str());
    }

    corrupt.sort_unstable();
    assert_eq!(
        corrupt,
        vec!["garbage.png", "truncated.jpg"],
        "the corpus must ship exactly the two corrupt fixtures (garbage.png, truncated.jpg); found {corrupt:?}"
    );
}

/// The corpus cannot silently lose a format, an awkward case, an EXIF
/// orientation, or the alpha-onto-white corner proof.
#[test]
fn corpus_covers_every_format_and_awkward_case() {
    let manifest = load_manifest();

    let mut observed_labels: BTreeSet<&str> = BTreeSet::new();
    let mut observed_tags: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    let mut orientation_summary: Vec<String> = Vec::new();
    let mut orientations: Vec<u8> = Vec::new();

    for fixture in &manifest.fixtures {
        // Derive the format from the same path the app sees, so a renamed
        // fixture cannot claim a format the app would not route to.
        let path = fixture_path(&fixture.file);
        let kind = InputKind::from_path(&path).unwrap_or_else(|| {
            panic!(
                "{} does not have an extension the app supports, so no format label can be derived for it",
                fixture.file
            )
        });
        // A format only counts as covered if the file that proves it is
        // actually there; a manifest entry alone is not a corpus.
        assert!(
            path.is_file(),
            "{} is missing from the fixture directory even though the manifest lists it; the corpus no longer contains the file that covers its {} format and {:?} tags",
            fixture.file,
            kind.label(),
            fixture.tags
        );
        observed_labels.insert(kind.label());

        let mut per_fixture: BTreeSet<&str> = BTreeSet::new();
        for tag in &fixture.tags {
            assert!(
                per_fixture.insert(tag.as_str()),
                "{} lists the tag {tag:?} more than once",
                fixture.file
            );
            observed_tags
                .entry(tag.as_str())
                .or_default()
                .push(fixture.file.as_str());
        }

        if let Some(orientation) = fixture.orientation {
            orientations.push(orientation);
            orientation_summary.push(format!("{}={orientation}", fixture.file));
        }
    }

    // --- all seven input formats, exactly ---
    let expected_labels: BTreeSet<&str> = REQUIRED_FORMAT_LABELS.into_iter().collect();
    let missing_labels: Vec<&str> = expected_labels
        .difference(&observed_labels)
        .copied()
        .collect();
    let unexpected_labels: Vec<&str> = observed_labels
        .difference(&expected_labels)
        .copied()
        .collect();
    assert!(
        missing_labels.is_empty() && unexpected_labels.is_empty(),
        "format coverage drifted: no fixture covers {missing_labels:?}, and {unexpected_labels:?} is not a supported input format; the corpus must cover exactly {REQUIRED_FORMAT_LABELS:?}"
    );

    // --- every required tag, at least once ---
    let missing_tags: Vec<&str> = REQUIRED_TAGS
        .into_iter()
        .filter(|tag| !observed_tags.contains_key(tag))
        .collect();
    assert!(
        missing_tags.is_empty(),
        "tag coverage drifted: no fixture carries {missing_tags:?}; every tag in {REQUIRED_TAGS:?} must appear at least once"
    );

    // --- EXIF orientations, exactly 1..=8 once each ---
    orientations.sort_unstable();
    let expected_orientations: Vec<u8> = (1..=8).collect();
    assert_eq!(
        orientations, expected_orientations,
        "orientation coverage drifted: recorded orientations are {orientation_summary:?} (sorted {orientations:?}) but the corpus must declare each of 1..=8 exactly once"
    );

    // The alpha-onto-white proof lives entirely in `jpeg_output.corners`, and
    // the conversion test simply skips the comparison when that block is null.
    // Guard its presence here so the proof cannot vanish silently.
    let alpha = manifest
        .fixtures
        .iter()
        .find(|fixture| fixture.file == "alpha.png")
        .unwrap_or_else(|| {
            panic!("the corpus has no alpha.png, the only fixture that records jpeg_output.corners")
        });
    let alpha_corners = alpha
        .jpeg_output
        .as_ref()
        .and_then(|jpeg| jpeg.corners.as_ref())
        .unwrap_or_else(|| {
            panic!(
                "alpha.png must record jpeg_output.corners; without them the alpha-onto-white check passes silently and the JPEG output could composite transparency onto anything"
            )
        });
    assert_eq!(
        alpha_corners.len(),
        CORNER_NAMES.len(),
        "alpha.png records {} jpeg_output corners but the corpus defines {} (top-left, top-right, bottom-left, bottom-right)",
        alpha_corners.len(),
        CORNER_NAMES.len()
    );
}

/// Two frames are the same picture when their pixel data and dimensions match;
/// delays and offsets are metadata, not image content.
fn frame_pixels_differ(first: &image::Frame, second: &image::Frame) -> bool {
    first.buffer().dimensions() != second.buffer().dimensions()
        || first.buffer().as_raw() != second.buffer().as_raw()
}

/// `anim.gif` must stay an animation: three frames, each one flat colour, and
/// no two of them the same picture.
#[test]
fn animated_gif_has_multiple_distinct_frames() {
    let manifest = load_manifest();
    let fixture = manifest
        .fixtures
        .iter()
        .find(|fixture| fixture.file == "anim.gif")
        .unwrap_or_else(|| panic!("the corpus has no anim.gif, so nothing proves animated input"));

    let path = fixture_path(&fixture.file);
    let file =
        File::open(&path).unwrap_or_else(|err| panic!("could not open {}: {err}", path.display()));
    // `decode::load` returns only the first frame, so the real GIF decoder is
    // required to see the animation at all.
    let decoder = image::codecs::gif::GifDecoder::new(BufReader::new(file))
        .unwrap_or_else(|err| panic!("anim.gif is not a decodable GIF: {err}"));
    let frames = decoder
        .into_frames()
        .collect_frames()
        .unwrap_or_else(|err| panic!("anim.gif frames do not decode: {err}"));

    let recorded = fixture.animation_frames.unwrap_or_else(|| {
        panic!(
            "anim.gif has no recorded animation_frames; the manifest must record the frame count"
        )
    });
    assert_eq!(
        frames.len(),
        usize::from(recorded),
        "anim.gif decodes to {} frames but the manifest records animation_frames = {recorded}",
        frames.len()
    );

    let mut corners_per_frame: Vec<Vec<[u8; 4]>> = Vec::new();
    for (index, frame) in frames.iter().enumerate() {
        let corners = rgba_corners(frame.buffer());
        let first = corners[0];
        for (corner_index, corner) in corners.iter().enumerate() {
            assert_eq!(
                *corner,
                first,
                "anim.gif frame {} is not uniform: {} corner is {corner:?} but the top-left corner is {first:?}",
                index + 1,
                CORNER_NAMES[corner_index]
            );
        }
        corners_per_frame.push(corners);
    }

    // Frame 2 must differ from frame 1, and frame 3 from both: full pixel
    // comparison, so a one-pixel edit still counts as a different frame.
    for (first, second) in [(0, 1), (0, 2), (1, 2)] {
        assert!(
            frame_pixels_differ(&frames[first], &frames[second]),
            "anim.gif frames {} and {} decode to identical pixels ({}x{}, corners {:?}); the fixture must stay a three-colour animation",
            first + 1,
            second + 1,
            frames[first].buffer().width(),
            frames[first].buffer().height(),
            corners_per_frame[first]
        );
    }
}

