//! Test-only integrity suite for the committed fixture corpus.
//!
//! `tests/fixtures/manifest.json` is the contract. Every value in it except
//! `bytes` and `sha256` is hand-authored from the feature spec; the ignored
//! `update_fixture_manifest` test is the only writer, and it refreshes only
//! those two generated fields plus the generated table block in
//! `tests/fixtures/README.md`.

