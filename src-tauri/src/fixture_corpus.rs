/// The manifest root, as written in `tests/fixtures/manifest.json`.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Manifest {
    pub version: u32,
    pub corner_tolerance: u8,
    pub fixtures: Vec<Fixture>,
}

/// One fixture entry.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Fixture {
    pub file: String,
    /// `InputKind::from_path(...).label()` for `file`.
    pub kind: String,
    pub tags: Vec<String>,
    pub about: String,
    /// Generated by `update_fixture_manifest`.
    pub bytes: u64,
    /// Lowercase hex SHA-256 of the file, generated by `update_fixture_manifest`.
    pub sha256: String,
    /// Per-channel source depth: 8, 12, or 16. `None` for corrupt fixtures.
    pub bit_depth: Option<u8>,
    /// EXIF orientation 1..=8, only for the eight orientation JPEGs.
    pub orientation: Option<u8>,
    /// Frame count, only for the animated GIF.
    pub animation_frames: Option<u8>,
    pub decoded: Option<DecodedFacts>,
    pub png_output: Option<PngOutput>,
    pub jpeg_output: Option<JpegOutput>,
    /// `Some("decode")` for fixtures that must fail to decode.
    pub error: Option<String>,
}

/// What `decode::load` must produce.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct DecodedFacts {
    pub width: u32,
    pub height: u32,
    /// `format!("{:?}", image.color())`, e.g. `Rgb8`.
    pub color: String,
    /// Top-left, top-right, bottom-left, bottom-right as 8-bit RGBA.
    pub corners: Vec<[u8; 4]>,
}

/// What the PNG output must be after conversion.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PngOutput {
    pub width: u32,
    pub height: u32,
    /// Always an 8-bit variant; `convert::encode` normalizes 16-bit input.
    pub color: String,
}

/// What the JPEG output must be after conversion. JPEG output is always
/// `Rgb8`, so only dimensions and (optionally) RGB corners are recorded.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct JpegOutput {
    pub width: u32,
    pub height: u32,
    pub corners: Option<Vec<[u8; 3]>>,
}

