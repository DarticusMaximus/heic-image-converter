/// Refresh the only generated fields (`bytes`, `sha256`) and the generated table
/// block in `README.md`. Refuses to run when the directory and manifest disagree
/// or the README markers are missing, and never touches `about`, tags, prose, or
/// any expectation.
#[test]
#[ignore = "rewrites bytes and sha256 in tests/fixtures/manifest.json and the table block in tests/fixtures/README.md"]
fn update_fixture_manifest() {
    let mut manifest = load_manifest();

    let on_disk: BTreeSet<String> = directory_fixture_names()
        .expect("read the fixture directory")
        .into_iter()
        .collect();
    let mut in_manifest = BTreeSet::new();
    for fixture in &manifest.fixtures {
        assert!(
            in_manifest.insert(fixture.file.clone()),
            "refusing to update: manifest lists {} more than once",
            fixture.file
        );
    }
    let missing: Vec<&String> = in_manifest.difference(&on_disk).collect();
    let stray: Vec<&String> = on_disk.difference(&in_manifest).collect();
    if !missing.is_empty() || !stray.is_empty() {
        panic!(
            "refusing to update: fixture directory and manifest disagree:\n  missing from disk: {missing:?}\n  not in manifest: {stray:?}"
        );
    }

    for fixture in &mut manifest.fixtures {
        let path = fixture_path(&fixture.file);
        let data = std::fs::read(&path)
            .unwrap_or_else(|err| panic!("could not read {}: {err}", path.display()));
        fixture.bytes = data.len() as u64;
        fixture.sha256 = sha256_hex(&data);
    }

    // Prepare the README before writing either file, so a missing README or a
    // missing marker fails the update without leaving the manifest rewritten.
    let readme_path = readme_path();
    let readme = std::fs::read_to_string(&readme_path).unwrap_or_else(|err| {
        panic!(
            "refusing to update: could not read {}: {err}; the README is hand-written and this test never creates it",
            readme_path.display()
        )
    });
    let refreshed = refresh_readme_table(&readme, &manifest)
        .unwrap_or_else(|detail| panic!("refusing to update: {}: {detail}", readme_path.display()));

    std::fs::write(manifest_path(), render_manifest(&manifest)).expect("write manifest");
    std::fs::write(&readme_path, refreshed).expect("write README");
}
