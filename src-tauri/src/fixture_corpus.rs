fn render_string(value: &str) -> String {
    serde_json::to_string(value).expect("strings always serialize")
}

fn render_rgba_corners(corners: &[[u8; 4]]) -> String {
    let parts: Vec<String> = corners
        .iter()
        .map(|c| format!("[{},{},{},{}]", c[0], c[1], c[2], c[3]))
        .collect();
    format!("[{}]", parts.join(","))
}

fn render_rgb_corners(corners: &[[u8; 3]]) -> String {
    let parts: Vec<String> = corners
        .iter()
        .map(|c| format!("[{},{},{}]", c[0], c[1], c[2]))
        .collect();
    format!("[{}]", parts.join(","))
}

fn render_optional_number(value: Option<u8>) -> String {
    value.map_or_else(|| "null".to_string(), |v| v.to_string())
}

/// Render the manifest exactly as committed: 2-space indent, inline corner
/// arrays, entries in authored order, trailing newline. Re-rendering a parsed
/// manifest is byte-identical, so the ignored update test is idempotent.
pub fn render_manifest(manifest: &Manifest) -> String {
    let mut out = String::new();
    out.push_str("{\n");
    out.push_str(&format!("  \"version\": {},\n", manifest.version));
    out.push_str(&format!(
        "  \"corner_tolerance\": {},\n",
        manifest.corner_tolerance
    ));
    out.push_str("  \"fixtures\": [\n");

    for (index, fixture) in manifest.fixtures.iter().enumerate() {
        out.push_str("    {\n");
        out.push_str(&format!(
            "      \"file\": {},\n",
            render_string(&fixture.file)
        ));
        out.push_str(&format!(
            "      \"kind\": {},\n",
            render_string(&fixture.kind)
        ));
        let tags: Vec<String> = fixture.tags.iter().map(|t| render_string(t)).collect();
        out.push_str(&format!("      \"tags\": [{}],\n", tags.join(",")));
        out.push_str(&format!(
            "      \"about\": {},\n",
            render_string(&fixture.about)
        ));
        out.push_str(&format!("      \"bytes\": {},\n", fixture.bytes));
        out.push_str(&format!(
            "      \"sha256\": {},\n",
            render_string(&fixture.sha256)
        ));
        out.push_str(&format!(
            "      \"bit_depth\": {},\n",
            render_optional_number(fixture.bit_depth)
        ));
        out.push_str(&format!(
            "      \"orientation\": {},\n",
            render_optional_number(fixture.orientation)
        ));
        out.push_str(&format!(
            "      \"animation_frames\": {},\n",
            render_optional_number(fixture.animation_frames)
        ));

        match &fixture.decoded {
            Some(decoded) => {
                out.push_str("      \"decoded\": {\n");
                out.push_str(&format!("        \"width\": {},\n", decoded.width));
                out.push_str(&format!("        \"height\": {},\n", decoded.height));
                out.push_str(&format!(
                    "        \"color\": {},\n",
                    render_string(&decoded.color)
                ));
                out.push_str(&format!(
                    "        \"corners\": {}\n",
                    render_rgba_corners(&decoded.corners)
                ));
                out.push_str("      },\n");
            }
            None => out.push_str("      \"decoded\": null,\n"),
        }

        match &fixture.png_output {
            Some(png) => out.push_str(&format!(
                "      \"png_output\": {{ \"width\": {}, \"height\": {}, \"color\": {} }},\n",
                png.width,
                png.height,
                render_string(&png.color)
            )),
            None => out.push_str("      \"png_output\": null,\n"),
        }

        match &fixture.jpeg_output {
            Some(jpeg) => {
                let corners = match &jpeg.corners {
                    Some(corners) => render_rgb_corners(corners),
                    None => "null".to_string(),
                };
                out.push_str(&format!(
                    "      \"jpeg_output\": {{ \"width\": {}, \"height\": {}, \"corners\": {} }},\n",
                    jpeg.width, jpeg.height, corners
                ));
            }
            None => out.push_str("      \"jpeg_output\": null,\n"),
        }

        match &fixture.error {
            Some(error) => out.push_str(&format!("      \"error\": {}\n", render_string(error))),
            None => out.push_str("      \"error\": null\n"),
        }

        out.push_str("    }");
        if index + 1 < manifest.fixtures.len() {
            out.push(',');
        }
        out.push('\n');
    }

    out.push_str("  ]\n");
    out.push_str("}\n");
    out
}

