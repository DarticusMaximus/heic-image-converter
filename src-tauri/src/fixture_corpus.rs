/// Files that live in the fixture directory without being fixtures themselves.
pub const NON_FIXTURE_FILES: [&str; 3] = ["README.md", "manifest.json", "generate.sh"];

/// Per-fixture size budget.
pub const MAX_FIXTURE_BYTES: u64 = 32 * 1024;

/// Whole-corpus size budget, fixtures only.
pub const MAX_CORPUS_BYTES: u64 = 64 * 1024;

/// The corner tolerance the corpus was authored for. Asserted, not read, so a
/// widened tolerance cannot silently gut every corner check.
pub const EXPECTED_CORNER_TOLERANCE: u8 = 8;

/// Corner order used by `decoded.corners`, for readable failure messages.
const CORNER_NAMES: [&str; 4] = ["top-left", "top-right", "bottom-left", "bottom-right"];

/// Every `InputKind::label()` the corpus must cover: all seven supported input
/// formats, no more and no less.
const REQUIRED_FORMAT_LABELS: [&str; 7] = ["heic", "jpeg", "png", "webp", "tiff", "bmp", "gif"];

/// Every awkward case the corpus exists to prove. Asserted here so a fixture
/// can never quietly stop carrying the tag that justifies its place.
const REQUIRED_TAGS: [&str; 10] = [
    "format-matrix",
    "alpha",
    "grayscale",
    "high-bit-depth",
    "animated-gif",
    "multi-image-heic",
    "heic-rotation",
    "exif-orientation",
    "corrupt",
    "truncated",
];

/// The only `error` value the integrity suite understands.
const DECODE_ERROR_KIND: &str = "decode";

