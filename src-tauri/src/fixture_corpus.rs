/// Markers that bracket the generated table in `tests/fixtures/README.md`.
const README_TABLE_BEGIN: &str = "<!-- BEGIN FIXTURE TABLE -->";
const README_TABLE_END: &str = "<!-- END FIXTURE TABLE -->";

/// Short corner labels for the table header and the JPEG corner cell.
const CORNER_LABELS: [&str; 4] = ["TL", "TR", "BL", "BR"];

/// `src-tauri/tests/fixtures/README.md`.
fn readme_path() -> PathBuf {
    fixture_dir().join("README.md")
}

/// The glyph a table cell uses when the manifest records nothing for it.
const EMPTY_CELL: &str = "—";

/// One corner as `#rrggbb`, or `#rrggbbaa` when the corner is not opaque.
fn render_corner_hex(corner: &[u8; 4]) -> String {
    let [red, green, blue, alpha] = *corner;
    if alpha == 255 {
        format!("#{red:02x}{green:02x}{blue:02x}")
    } else {
        format!("#{red:02x}{green:02x}{blue:02x}{alpha:02x}")
    }
}

/// The four decoded corners in TL/TR/BL/BR order, space separated.
fn render_corner_cell(fixture: &Fixture, corners: &[[u8; 4]]) -> String {
    assert_eq!(
        corners.len(),
        CORNER_LABELS.len(),
        "{}: the manifest records {} corners but the corner convention has {} (TL/TR/BL/BR)",
        fixture.file,
        corners.len(),
        CORNER_LABELS.len()
    );
    corners
        .iter()
        .map(render_corner_hex)
        .collect::<Vec<String>>()
        .join(" ")
}

/// A number, or the empty-cell glyph when the manifest records `null`.
fn render_optional_cell(value: Option<u8>) -> String {
    value.map_or_else(|| EMPTY_CELL.to_string(), |v| v.to_string())
}

/// Decoded dimensions and colour, or the recorded decode error.
fn render_decoded_cell(fixture: &Fixture) -> String {
    match &fixture.decoded {
        Some(decoded) => format!("{}x{} {}", decoded.width, decoded.height, decoded.color),
        None => match fixture.error.as_deref() {
            Some(error) => format!("{error} error"),
            None => panic!(
                "{}: the manifest records neither decoded facts nor a decode error, so the README table cannot describe it",
                fixture.file
            ),
        },
    }
}

/// Decoded corners, or the empty-cell glyph for a corrupt fixture.
fn render_decoded_corners_cell(fixture: &Fixture) -> String {
    match &fixture.decoded {
        Some(decoded) => render_corner_cell(fixture, &decoded.corners),
        None => EMPTY_CELL.to_string(),
    }
}

/// PNG output dimensions and colour (always an 8-bit variant).
fn render_png_cell(fixture: &Fixture) -> String {
    match &fixture.png_output {
        Some(png) => format!("{}x{} {}", png.width, png.height, png.color),
        None if fixture.error.is_some() => EMPTY_CELL.to_string(),
        None => panic!(
            "{}: the manifest records no png_output and no decode error, so the README table cannot describe it",
            fixture.file
        ),
    }
}

/// JPEG output dimensions, plus the recorded RGB corners when there are any.
fn render_jpeg_cell(fixture: &Fixture) -> String {
    let Some(jpeg) = &fixture.jpeg_output else {
        if fixture.error.is_some() {
            return EMPTY_CELL.to_string();
        }
        panic!(
            "{}: the manifest records no jpeg_output and no decode error, so the README table cannot describe it",
            fixture.file
        );
    };

    let mut cell = format!("{}x{}", jpeg.width, jpeg.height);
    if let Some(corners) = &jpeg.corners {
        assert_eq!(
            corners.len(),
            CORNER_LABELS.len(),
            "{}: the manifest records {} jpeg_output corners but the corner convention has {} (TL/TR/BL/BR)",
            fixture.file,
            corners.len(),
            CORNER_LABELS.len()
        );
        for (label, corner) in CORNER_LABELS.iter().zip(corners) {
            let _ = write!(
                cell,
                "; {label} #{:02x}{:02x}{:02x}",
                corner[0], corner[1], corner[2]
            );
        }
    }
    cell
}

/// EXIF orientation and/or frame count, whichever the manifest records.
fn render_extras_cell(fixture: &Fixture) -> String {
    let mut parts: Vec<String> = Vec::new();
    if let Some(orientation) = fixture.orientation {
        parts.push(format!("orientation {orientation}"));
    }
    if let Some(frames) = fixture.animation_frames {
        parts.push(format!("{frames} frames"));
    }
    if parts.is_empty() {
        EMPTY_CELL.to_string()
    } else {
        parts.join(", ")
    }
}

/// Tags, each in backticks, in the manifest's authored order.
fn render_tags_cell(fixture: &Fixture) -> String {
    if fixture.tags.is_empty() {
        EMPTY_CELL.to_string()
    } else {
        fixture
            .tags
            .iter()
            .map(|tag| format!("`{tag}`"))
            .collect::<Vec<String>>()
            .join(", ")
    }
}

/// Render the fixture table from the manifest alone: one row per fixture, one
/// column per recorded fact, trailing newline. Both the freshness test and the
/// ignored updater call this, so they cannot disagree about what the table says.
pub fn render_readme_table(manifest: &Manifest) -> String {
    let mut out = String::new();
    out.push_str("| File | Kind | Bytes | Bits | Decoded | Corners (TL/TR/BL/BR) | PNG out | JPEG out | Extras | Tags |\n");
    out.push_str("| --- | --- | ---: | ---: | --- | --- | --- | --- | --- | --- |\n");

    for fixture in &manifest.fixtures {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
            fixture.file,
            fixture.kind,
            fixture.bytes,
            render_optional_cell(fixture.bit_depth),
            render_decoded_cell(fixture),
            render_decoded_corners_cell(fixture),
            render_png_cell(fixture),
            render_jpeg_cell(fixture),
            render_extras_cell(fixture),
            render_tags_cell(fixture),
        );
    }

    out
}

/// Locate the single BEGIN/END marker pair, returning the byte offsets of the
/// marker texts themselves. Rejects missing, duplicated, or inverted markers.
fn readme_marker_offsets(readme: &str) -> Result<(usize, usize), String> {
    let begins: Vec<usize> = readme
        .match_indices(README_TABLE_BEGIN)
        .map(|(at, _)| at)
        .collect();
    let ends: Vec<usize> = readme
        .match_indices(README_TABLE_END)
        .map(|(at, _)| at)
        .collect();

    if begins.len() != 1 {
        return Err(format!(
            "expected exactly one {README_TABLE_BEGIN:?} marker in README.md, found {}",
            begins.len()
        ));
    }
    if ends.len() != 1 {
        return Err(format!(
            "expected exactly one {README_TABLE_END:?} marker in README.md, found {}",
            ends.len()
        ));
    }

    let (begin, end) = (begins[0], ends[0]);
    if end < begin + README_TABLE_BEGIN.len() {
        return Err(format!(
            "{README_TABLE_END:?} appears before {README_TABLE_BEGIN:?} in README.md"
        ));
    }
    Ok((begin, end))
}

/// What the README must hold strictly between the two markers: one newline, the
/// rendered table, and the table's own trailing newline.
fn expected_readme_interior(manifest: &Manifest) -> String {
    format!("\n{}", render_readme_table(manifest))
}

/// Splice the table rendered from `manifest` between the README's markers and
/// return the whole updated file. The markers themselves and every byte of
/// prose outside them are preserved.
fn refresh_readme_table(readme: &str, manifest: &Manifest) -> Result<String, String> {
    let (begin, end) = readme_marker_offsets(readme)?;
    Ok(format!(
        "{}{}{}",
        &readme[..begin + README_TABLE_BEGIN.len()],
        expected_readme_interior(manifest),
        &readme[end..]
    ))
}

/// Explain the first disagreement between the committed block and the rendered
/// table, so a stale README points at the offending row.
fn describe_block_difference(actual: &str, expected: &str) -> String {
    let actual_lines: Vec<&str> = actual.lines().collect();
    let expected_lines: Vec<&str> = expected.lines().collect();

    for (index, (got, want)) in actual_lines.iter().zip(&expected_lines).enumerate() {
        if got != want {
            return format!(
                "line {} disagrees:\n    README:   {got}\n    manifest: {want}",
                index + 1
            );
        }
    }

    if actual_lines.len() != expected_lines.len() {
        let shared = actual_lines.len().min(expected_lines.len());
        let (extra, which) = if actual_lines.len() > expected_lines.len() {
            (actual_lines.get(shared), "README")
        } else {
            (expected_lines.get(shared), "manifest")
        };
        return format!(
            "the block has {} lines but the manifest renders {}; first extra line from the {which}: {:?}",
            actual_lines.len(),
            expected_lines.len(),
            extra.copied().unwrap_or("")
        );
    }

    "the block matches line by line but differs in trailing whitespace or newlines".to_string()
}

/// The README's generated table must equal the table rendered from the manifest.
#[test]
fn readme_table_is_current() {
    let manifest = load_manifest();
    let path = readme_path();
    let readme = std::fs::read_to_string(&path).unwrap_or_else(|err| {
        panic!(
            "could not read {}: {err}; the fixture README documents the manifest and must exist",
            path.display()
        )
    });

    let (begin, end) = readme_marker_offsets(&readme)
        .unwrap_or_else(|detail| panic!("{}: {detail}", path.display()));

    let actual = &readme[begin + README_TABLE_BEGIN.len()..end];
    let expected = expected_readme_interior(&manifest);
    if actual == expected {
        return;
    }

    panic!(
        "{}: the fixture table between {README_TABLE_BEGIN:?} and {README_TABLE_END:?} is stale — it no longer matches the manifest ({}); run `cargo test -- --ignored update_fixture_manifest` to regenerate the block",
        path.display(),
        describe_block_difference(actual, &expected)
    );
}

