/// `decoded.color` is compared as this string.
pub fn color_debug_name(color: image::ColorType) -> String {
    format!("{color:?}")
}

/// 16-bit color types imply a per-channel depth of 16; everything else is 8.
/// HEIC is checked with the seam's `heic::probe` instead, because a 10- or
/// 12-bit HEIC decodes into a 16-bit `image` color type.
pub fn color_derived_bit_depth(color: image::ColorType) -> u8 {
    use image::ColorType::*;
    match color {
        L16 | La16 | Rgb16 | Rgba16 => 16,
        _ => 8,
    }
}

/// Map the seam's bit depth onto the manifest's per-channel depth.
pub fn seam_bit_depth(depth: crate::heic::BitDepth) -> u8 {
    depth.as_u8()
}

/// Sample the four corners of an RGBA8 buffer at top-left, top-right,
/// bottom-left, bottom-right.
fn rgba_corners(rgba: &image::RgbaImage) -> Vec<[u8; 4]> {
    let (width, height) = rgba.dimensions();
    assert!(
        width > 0 && height > 0,
        "cannot sample corners of an empty image"
    );
    let points = [
        (0, 0),
        (width - 1, 0),
        (0, height - 1),
        (width - 1, height - 1),
    ];
    points
        .iter()
        .map(|&(x, y)| rgba.get_pixel(x, y).0)
        .collect()
}

/// Sample the decoded image at top-left, top-right, bottom-left,
/// bottom-right as 8-bit RGBA.
pub fn sample_corners(image: &image::DynamicImage) -> Vec<[u8; 4]> {
    rgba_corners(&image.to_rgba8())
}

/// Compare RGBA corners per channel, allowing `tolerance` of absolute
/// difference on each channel.
pub fn corners_match(
    actual: &[[u8; 4]],
    expected: &[[u8; 4]],
    tolerance: u8,
) -> Result<(), String> {
    if actual.len() != expected.len() {
        return Err(format!(
            "expected {} corners, sampled {}",
            expected.len(),
            actual.len()
        ));
    }
    for (index, (got, want)) in actual.iter().zip(expected).enumerate() {
        let corner = CORNER_NAMES.get(index).copied().unwrap_or("corner");
        for channel in 0..4 {
            let diff = got[channel].abs_diff(want[channel]);
            if diff > tolerance {
                return Err(format!(
                    "{corner} corner channel {channel}: decoded {} but recorded {} (diff {diff} > tolerance {tolerance})",
                    got[channel], want[channel]
                ));
            }
        }
    }
    Ok(())
}

/// JPEG output is RGB, so its corners drop the (always opaque) alpha channel
/// that `sample_corners` returns.
pub fn sample_rgb_corners(image: &image::DynamicImage) -> Vec<[u8; 3]> {
    sample_corners(image)
        .into_iter()
        .map(|[red, green, blue, _alpha]| [red, green, blue])
        .collect()
}

/// Compare RGB corners (JPEG output) per channel, allowing `tolerance`.
pub fn rgb_corners_match(
    actual: &[[u8; 3]],
    expected: &[[u8; 3]],
    tolerance: u8,
) -> Result<(), String> {
    if actual.len() != expected.len() {
        return Err(format!(
            "expected {} corners, sampled {}",
            expected.len(),
            actual.len()
        ));
    }
    for (index, (got, want)) in actual.iter().zip(expected).enumerate() {
        let corner = CORNER_NAMES.get(index).copied().unwrap_or("corner");
        for channel in 0..3 {
            let diff = got[channel].abs_diff(want[channel]);
            if diff > tolerance {
                return Err(format!(
                    "{corner} corner channel {channel}: encoded {} but recorded {} (diff {diff} > tolerance {tolerance})",
                    got[channel], want[channel]
                ));
            }
        }
    }
    Ok(())
}

